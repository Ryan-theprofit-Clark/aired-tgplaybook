#!/usr/bin/env node
/**
 * Embed the Mirror diagnostic quiz into the worker bundle.
 *
 * Source of truth for the quiz page:
 *   /Users/rcclark/Documents/the-mirror-outreach/diagnostic/index.html
 *
 * After editing the quiz, run from apps/worker:
 *   node scripts/embed-mirror-quiz.mjs
 *   npx wrangler deploy --config wrangler.mirror.toml
 *
 * A TS string module (instead of a wrangler Text rule) keeps the other
 * tenant configs untouched — no [[rules]] additions needed anywhere.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const SRC = "/Users/rcclark/Documents/the-mirror-outreach/diagnostic/index.html";
const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, "..", "src", "quiz");
const outFile = join(outDir, "mirror-quiz.ts");

const html = readFileSync(SRC, "utf8");
const token = "'__MIRROR_BOOT__'";
const count = html.split(token).length - 1;
if (count !== 1) {
  console.error(`ABORT: injection token ${token} must appear exactly once in the quiz source (found ${count}).`);
  process.exit(1);
}

mkdirSync(outDir, { recursive: true });
writeFileSync(
  outFile,
  `// GENERATED by scripts/embed-mirror-quiz.mjs — do not edit by hand.\n` +
  `// Source of truth: ${SRC}\n` +
  `export const QUIZ_HTML: string = ${JSON.stringify(html)};\n`,
);
console.log(`embedded ${html.length} bytes -> ${outFile}`);
